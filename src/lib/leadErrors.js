export function leadFailureText(result, { keepCart = false } = {}) {
  if (result?.status === 429) return "Слишком много заявок. Подождите и попробуйте снова.";
  if (!result?.status) {
    return keepCart
      ? "Сервер сейчас недоступен. Заказ не сохранён, корзина на месте. Попробуйте ещё раз."
      : "Сервер сейчас недоступен. Заявка не отправлена. Попробуйте ещё раз.";
  }
  return keepCart
    ? "Не получилось сохранить заказ. Корзина не изменена. Попробуйте ещё раз."
    : "Не получилось сохранить заявку. Попробуйте ещё раз.";
}
