function bundle(lang) {
  return lang === "kk" ? copy.kk : copy.ru;
}

function listBundle(lang) {
  return lang === "kk" ? lists.kk : lists.ru;
}

export function text(lang, key) {
  const value = bundle(lang)[key];
  return value === undefined ? copy.ru[key] : value;
}

export function list(lang, key) {
  const value = listBundle(lang)[key];
  return value === undefined ? lists.ru[key] : value;
}

export function presentService(service, lang = getLang()) {
  if (!service || lang !== "kk") return service;
  const origin = catalog.find((item) => item.id === service.id);
  const translated = kkServices[service.id];
  if (!origin || !translated) return service;
  const same = (field) => String(service[field] || "").trim() === origin[field];
  return {
    ...service,
    title: same("title") ? translated.title : service.title,
    description: same("description") ? translated.description : service.description,
    result: same("result") ? translated.result : service.result,
  };
}

export function objectChoices(lang = getLang()) {
  const labels = list(lang, "objectsSelect");
  return OBJECT_TYPES.map((value, index) => ({
    value,
    label: labels[index] || value,
  }));
}

export function objectLabel(value, lang = getLang()) {
  return objectChoices(lang).find((item) => item.value === value)?.label || value;
}

export function checklistVerdict(done, total, lang = getLang()) {
  const [empty, gaps, almost, ready] = list(lang, "verdicts");
  if (done === 0) return empty;
  if (done === total) return ready;
  if (done >= total - 2) return almost;
  return gaps;
}

export function leadText(result, { keepCart = false, lang = getLang() } = {}) {
  const strings = listBundle(lang);
  if (result?.status === 429) return strings.leadRate;
  if (!result?.status) return keepCart ? strings.leadOfflineOrder : strings.leadOfflineRequest;
  return keepCart ? strings.leadFailOrder : strings.leadFailRequest;
}

export function serviceCount(amount, lang, ruCount) {
  if (lang === "kk") return `${amount} қызмет`;
  return ruCount(amount, "услуга", "услуги", "услуг");
}
