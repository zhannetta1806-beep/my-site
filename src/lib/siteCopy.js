const LANG_KEY = "sanexpert-lang";

let active = "ru";

export function getLang() {
  return active;
}

export function setActiveLang(lang) {
  active = lang === "kk" ? "kk" : "ru";
  return active;
}

export function readStoredLang() {
  try {
    return localStorage.getItem(LANG_KEY) === "kk" ? "kk" : "ru";
  } catch {
    return "ru";
  }
}

export function storeLang(lang) {
  const value = setActiveLang(lang);
  try {
    localStorage.setItem(LANG_KEY, value);
  } catch {
    /* выбор языка останется до обновления страницы */
  }
  return value;
}

